/** Interactive regression check; run with Vite on port 1420. */
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { generate } from '../src/generators/generate';
import { landmarkMapBounds } from '../src/core/environment';

const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const assert = (condition: unknown, message: string) => { if (!condition) throw new Error(message); };
try {
  await mkdir('test-results', { recursive: true });
  await page.goto('http://127.0.0.1:1420');
  const controls = page.getByRole('region', { name: 'Входы и выходы', exact: true });
  await controls.waitFor();
  const count = () => controls.locator('li').count();
  const maze = generate({ columns: 5, rows: 5, moduleSize: 2, corridorWidth: 2, extraConnections: 0, seed: '', algorithm: 'prim' });
  const bounds = landmarkMapBounds(maze), centerX = (bounds.minX+bounds.maxX)/2, centerZ = (bounds.minZ+bounds.maxZ)/2;
  const clickMap = async (x: number, z: number, zoom = 1) => {
    const canvas = page.locator('.map-canvas');
    await canvas.scrollIntoViewIfNeeded();
    let rect = await canvas.boundingBox();
    if (!rect) throw new Error('Missing map');
    const scale = Math.max(0.1, Math.min((rect.width-150)/(bounds.maxX-bounds.minX), (rect.height-160)/(bounds.maxZ-bounds.minZ))*zoom);
    const targetY = rect.y+rect.height/2+(z-centerZ)*scale;
    await page.evaluate(y => window.scrollBy(0, y-window.innerHeight/2), targetY);
    rect = await canvas.boundingBox();
    if (!rect) throw new Error('Missing map after scroll');
    await page.mouse.click(rect.x+rect.width/2+(x-centerX)*scale, rect.y+rect.height/2+(z-centerZ)*scale);
  };
  await controls.getByRole('button', { name: '+ Добавить вход-выход', exact: true }).click();
  await clickMap(9, 0);
  await controls.locator('li').nth(2).waitFor();
  assert(await count() === 3, 'Click must add a third opening');
  await controls.getByRole('button', { name: '+ Добавить вход-выход', exact: true }).click();
  await clickMap(9, 0);
  assert(await count() === 3, 'Duplicate openings must not be added');
  await page.getByRole('alert').filter({ hasText: 'Здесь уже есть вход-выход' }).waitFor();
  await controls.getByRole('button', { name: 'Отмена', exact: true }).click();
  await controls.getByLabel('Переместить проём 3', { exact: true }).click();
  await clickMap(5, 18);
  assert((await controls.locator('li').nth(2).innerText()).includes('Юг'), 'Move must update the side');
  await controls.getByLabel('Старт', { exact: true }).selectOption('1');
  assert(await controls.getByLabel('Финиш', { exact: true }).inputValue() === '0', 'Selecting the existing finish as start must swap the pair');
  await controls.getByLabel('Старт', { exact: true }).selectOption('2');
  await controls.getByLabel('Финиш', { exact: true }).selectOption('0');
  await controls.getByRole('button', { name: '⇄ Поменять местами', exact: true }).click();
  assert(await controls.getByLabel('Старт', { exact: true }).inputValue() === '0', 'Reverse must select the old finish');
  assert(await controls.getByLabel('Финиш', { exact: true }).inputValue() === '2', 'Reverse must select the old start');
  await page.getByLabel('Кратчайший путь', { exact: true }).check();
  await page.getByRole('button', { name: 'Отдалить', exact: true }).click();
  await controls.getByRole('button', { name: '+ Добавить вход-выход', exact: true }).click();
  await clickMap(0, 9, 0.8);
  assert(await count() === 4, 'Zoomed map must place a fourth opening');
  await controls.getByLabel('Удалить проём 4', { exact: true }).click();
  await page.getByRole('button', { name: 'Сгенерировать', exact: true }).click();
  assert(await count() === 3, 'Regeneration must retain placed openings');
  const pendingDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await (await pendingDownload).saveAs('test-results/portals.json');
  const saved = JSON.parse(await Bun.file('test-results/portals.json').text());
  assert(saved.portals.length === 3 && saved.exit.side === 'south' && saved.exit.cell === 74, 'Saved pair and moved portal must match');
  await controls.getByLabel('Удалить проём 3', { exact: true }).click();
  assert(await count() === 2, 'Deletion must remove the selected endpoint');
  assert(await controls.getByLabel('Удалить проём 1', { exact: true }).isDisabled(), 'Two openings are the minimum');
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Открыть', exact: true }).click();
  await (await chooser).setFiles('test-results/portals.json');
  await page.waitForFunction(() => document.querySelectorAll('.portal-controls li').length === 3);
  assert(await controls.getByLabel('Финиш', { exact: true }).inputValue() === '2', 'Load must restore the selected pair');
  await page.screenshot({ path: 'test-results/portals-map.png', fullPage: true });
  await page.getByRole('button', { name: /Пройти от первого лица/ }).click();
  await page.getByRole('button', { name: /Начать прохождение/ }).waitFor();
  await page.waitForFunction(() => (document.querySelector<HTMLCanvasElement>('.walk-canvas')?.width ?? 0) > 300);
  assert((await page.locator('.walk-hud').innerText()).includes('СТАРТ 1 → ФИНИШ 3'), '3D must use the selected pair');
  await page.getByRole('button', { name: '← Вернуться к карте', exact: true }).click();
  await controls.waitFor();
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('PASS: add, move, zoomed placement, selected pair, reverse, regenerate, delete, JSON roundtrip and 3D.');
} finally { await browser.close(); }
